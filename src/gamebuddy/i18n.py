# Omarchy locale codes that share a table: one Portuguese besides Brazil, and
# Spanish is the same whichever country Omarchy names.
_ALIASES = {"pt": "pt-PT", "es-MX": "es"}

OMARCHY_LANGUAGE_FILE = Path.home() / ".config" / "omarchy" / "language"


def is_rtl(language: str) -> bool:
    return language in RTL_LANGUAGES


def omarchy_language() -> str:
    """The code chosen in Omarchy's Setup > Language, or "" when unset."""
    try:
        return OMARCHY_LANGUAGE_FILE.read_text().strip().splitlines()[0].strip()
    except (OSError, IndexError):
        return ""


def _resolve(raw: str) -> str:
    """Map an Omarchy code or a POSIX locale onto one of our tables."""
    code = (raw or "").split(".")[0].replace("_", "-").strip()
    if code in _ALIASES:
        return _ALIASES[code]
    if code in _STRINGS:
        return code
    lower = code.lower()
    if lower.startswith("pt"):
        return "pt-BR" if lower.endswith("-br") else "pt-PT"
    if lower.startswith("zh"):
        return "zh-CN" if lower.endswith("-cn") or "hans" in lower else "zh-TW"
    short = lower.split("-")[0]
    return _ALIASES.get(short, short)


def _env_language() -> str:
    for var in ("LC_ALL", "LC_MESSAGES", "LANG"):
        value = os.environ.get(var)
        if value:
            return value
    try:
        return locale.getlocale()[0] or ""
    except ValueError:
        return ""


def detect_language() -> str:
    for raw in (omarchy_language(), _env_language()):
        code = _resolve(raw)
        if code in _STRINGS:
            return code
    return "en"


class Translator:
    def __init__(self, language: str = "auto"):
        self.set_language(language)

    def set_language(self, language: str) -> None:
        self.language = detect_language() if language == "auto" else language
        if self.language not in _STRINGS:
            self.language = "en"

    def __call__(self, _key: str, **kwargs: object) -> str:
        table = _STRINGS.get(self.language, _STRINGS["en"])
        text = table.get(_key) or _STRINGS["en"].get(_key) or _key
        try:
            return text.format(**kwargs) if kwargs else text
        except (KeyError, IndexError):
            return text


def language_display_name(code: str) -> str:
    return LANGUAGE_NAMES.get(code, code)
